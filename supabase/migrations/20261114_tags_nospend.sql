-- Insight features: transaction labels (tags) and "Mode Hemat" settings.
-- Run once in the Supabase SQL editor. The app detects these objects and keeps
-- the features hidden (or read-only) until they exist, so running this is safe
-- at any time and running it twice changes nothing.

-- Labels the user creates themselves (e.g. "Liburan Bali", "Nikahan").
create table if not exists public.tags (
  id bigint generated by default as identity primary key,
  name text not null,
  color text not null default 'teal',
  emoji text,
  created_at timestamptz not null default now()
);

create unique index if not exists tags_name_unique on public.tags (lower(name));

-- A transaction can carry any number of labels. IDs (not names) are stored,
-- so renaming a label never breaks old transactions.
alter table public.transactions
  add column if not exists tag_ids bigint[] not null default '{}';

create index if not exists transactions_tag_ids_gin on public.transactions using gin (tag_ids);

-- Mode Hemat settings: which categories count as "jajan" and the streak target.
-- Shape: { "categories": ["Makan di Luar", ...], "target": 7 }
alter table public.user_settings
  add column if not exists nospend jsonb;

